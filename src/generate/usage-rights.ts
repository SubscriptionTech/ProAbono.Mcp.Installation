/**
 * Code generation for In-Site Step 3 -- reading, caching and enforcing a customer's rights.
 *
 * Seven rules of spec section 11 are carried into every stack, because each one is a way the
 * integration is wrong without ever failing:
 *
 *  1. nothing branches on `ReferenceOffer`; rights come from the Usage API;
 *  2. the cache is **replaced** wholesale on refresh, never merged -- a Feature that dropped out
 *     of the response must drop out of the cache;
 *  3. `IsEnabled` is enforced for `OnOff`, not `IsIncluded`;
 *  4. an absent `QuantityCurrent` means **unlimited**, not zero, and it may exceed
 *     `QuantityIncluded`;
 *  5. the collection is read to `TotalItems`, never one page;
 *  6. a failed read serves the last known good cache and raises an alert -- never zero rights and
 *     never a cleared session;
 *  7. an empty response is diagnosed, not reported as "no rights".
 *
 * And the expiry policy, which is what makes the cache honest: an entry expires at
 * min(`DatePeriodEnd`, MAX_TTL), a customer's expiry is the **earliest** `DatePeriodEnd` across
 * their Usages, and no `DatePeriodEnd` falls back to MAX_TTL.
 */
import type { Stack } from "./hosted-pages.js";

/**
 * The ceiling on a cached entry, in seconds.
 *
 * `DatePeriodEnd` is the primary expiry; this caps the damage when the webhook that should have
 * invalidated the entry never arrives -- which is every installation until the notification
 * endpoint is validated, and this release ships no endpoint at all (see `MISSING_RESYNC`).
 */
export const MAX_TTL_SECONDS = 900;

/**
 * What this release does not generate, stated in the tool's own output.
 *
 * Spec section 11 wires the resynchronization onto the notification endpoint that
 * `scaffold_notification_endpoint` produces. That tool is not in this release, so there is no
 * endpoint to wire onto -- and a developer must not ship this cache believing the webhook path
 * exists behind it.
 */
export const MISSING_RESYNC =
  "The resynchronization function and its webhook wiring are **not** generated by this version. " +
  "Spec-wise they belong here: one notification endpoint, one global resync of the affected " +
  "customer, taken from `Customer.ReferenceCustomer` and never from `CustomerBuyer`. Until the " +
  "endpoint scaffold ships, the maximum TTL above is the only thing bounding a stale entry: a " +
  "right revoked in ProAbono stays served for up to that long. Keep the ceiling short while you " +
  "are in that window, and re-read rights behind every redirect into a protected area.";

