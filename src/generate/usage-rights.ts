    "        var ends = usages.Where(u => u.DatePeriodEnd is not null).Select(u => u.DatePeriodEnd!.Value).ToList();",
    "",
    "        return ends.Count == 0 ? ceiling : ends.Append(ceiling).Min();",
    "    }",
    "",
    "    private sealed record Entry(List<Usage> Usages, DateTimeOffset ExpiresAt);",
    "}",
    "",
    "public sealed class Rights",
    "{",
    "    private readonly Dictionary<string, Usage> _byFeature;",
    "",
    "    public Rights(List<Usage> usages)",
