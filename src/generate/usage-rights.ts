/**
 * The rights module: the read, the cache, the expiry and the gates, in the idiom of the stack.
 *
 * One module per stack rather than one generic sketch, because the failure modes are in the
 * details -- pagination, an absent quantity, the expiry arithmetic -- and a developer translating
 * a sketch is where those details get lost.
 */
export function rightsModule(stack: Stack): string {
  switch (stack) {
    case "node-express":
    case "next":
      return nodeRightsModule();
    case "php":
      return phpRightsModule();
    case "python":
      return pythonRightsModule();
    case "ruby":
      return rubyRightsModule();
    case "csharp":
      return csharpRightsModule();
    case "generic":
      return genericRightsModule();
  }
}

