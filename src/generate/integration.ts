/**
 * The generic code generator: an authenticated ProAbono call, in the project's own language.
 *
 * It exists for the journeys no task-specific generator covers. What it must never become is a
 * second, weaker version of those generators -- `install_customer_portal`, `generate_pricing_table`
 * and `sync_usage_rights` each carry rules a generic generator cannot know, and they stay. So this
 * module generates the part that is the same everywhere and is where integrations actually go
 * wrong:
 *
 *  - **Basic auth read from configuration**, Agent key as username, API key as password, never
 *    inlined -- the guardrail of spec section 8, and the one a hand-written snippet breaks first.
 *  - **The Segment carried on every operation that declares it.** Omitted, ProAbono answers for the
 *    Business's default Segment with no error at all, and a `ReferenceCustomer` is unique per
 *    Segment. `/v1/Usages` is the single exception, and it is an exception *in the contract*.
 *  - **Collections read to `TotalItems`**, never one page, and `204 No Content` read as an empty
 *    collection rather than parsed.
 *  - **The customer reference from the session**, never from the request.
 *
 * Everything it says about an operation comes from the contract, at generation time. Nothing here
 * remembers an endpoint.
 */
