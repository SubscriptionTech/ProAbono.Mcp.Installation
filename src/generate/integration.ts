/**
 * Resolves a language name to a stack, or reports that it could not.
 *
 * An unrecognised language is answered with the generic sketch **and told so**, rather than
 * silently generating JavaScript for a Go project. The HTTP calls themselves are
 * language-independent and are what the generic answer carries.
 */
export function resolveLanguage(language: string): { stack: Stack; recognised: boolean } {
  const key = language.trim().toLowerCase();
  const stack = LANGUAGE_ALIASES[key];
  return stack === undefined ? { stack: "generic", recognised: false } : { stack, recognised: true };
}

