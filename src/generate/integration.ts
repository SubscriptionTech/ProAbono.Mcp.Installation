        "  const url = new URL(`${process.env.PROABONO_API_BASE}${path}`);",
        "",
        "  // The Segment, on every operation that declares one. /v1/Usages is the exception: the",
        "  // contract declares none there, so none is sent -- not a shortcut, the contract.",
        '  if (!path.startsWith("/v1/Usages") && query.ReferenceSegment === undefined) {',
        '    url.searchParams.set("ReferenceSegment", process.env.PROABONO_SEGMENT_REF);',
        "  }",
        "  for (const [name, value] of Object.entries(query)) {",
        "    if (value !== undefined) url.searchParams.set(name, String(value));",
        "  }",
        "",
        "  const response = await fetch(url, {",
        "    method,",
        "    headers: {",
        "      Authorization: AUTHORIZATION,",
        '      Accept: "application/json",',
        '      ...(body === undefined ? {} : { "Content-Type": "application/json" }),',
        "    },",
        "    ...(body === undefined ? {} : { body: JSON.stringify(body) }),",
        "  });",
        "",
        "  if (!response.ok) {",
        "    // ProAbono answers with its own Code, which is what the documentation is indexed on.",
        "    const detail = await response.text();",
        "    throw new Error(`ProAbono ${method} ${path} -> ${response.status}: ${detail}`);",
        "  }",
        "",
        "  // 204 No Content: an empty record or an empty collection. There is no body to parse.",
        "  if (response.status === 204) return undefined;",
        "  return response.json();",
        "}",
        "",
        "// Every collection, read whole. One page is a subset and looks exactly like the whole set.",
        "export async function proabonoList(path, query = {}) {",
        "  const items = [];",
        "  let page = 1;",
        "",
        "  for (;;) {",
        "    const payload = await proabono(\"GET\", path, {",
        "      query: { ...query, Page: page, SizePage: 200 },",
