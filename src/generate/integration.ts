        "",
        "  request = Net::HTTPGenericRequest.new(method, body ? true : false, true, uri)",
        "  request['Authorization'] = 'Basic ' + [\"#{ENV.fetch('PROABONO_AGENT_KEY')}:#{ENV.fetch('PROABONO_API_KEY')}\"].pack('m0')",
