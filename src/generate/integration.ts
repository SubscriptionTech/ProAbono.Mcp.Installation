        "  # The Segment, on every operation that declares one. /v1/Usages is the exception: the",
        "  # contract declares none there, so none is sent.",
        "  query = query.dup",
        "  query['ReferenceSegment'] ||= ENV.fetch('PROABONO_SEGMENT_REF') unless path.start_with?('/v1/Usages')",
